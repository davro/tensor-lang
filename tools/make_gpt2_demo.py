#!/usr/bin/env python3
"""Generate a TensorLang program that runs real GPT-2 (from tools/export_gpt2_weights.py), plus a float64
NumPy reference for the same prompt.

    python3 tools/make_gpt2_demo.py --prompt "The capital of France is"
    python3 tensorlang.py build/gpt2_forward.tl          # prints the predicted next-token id, saves logits
    python3 tools/compare_gpt2_logits.py                 # TensorLang logits vs the float64 reference

Options:
    --weights DIR      exported weights (default build/gpt2)
    --ids 464,3139     use token ids instead of --prompt (no tokenizer needed)
    --out FILE         generated program (default build/gpt2_forward.tl)
    --ref-generate N   also print N greedy tokens from the NumPy reference (sanity check on the reference)
    --shapes-only      do not read weights: emit the GPT-2-small program for type checking only

The program is unrolled (one call of the fn gpt2_block per layer) because load() takes a string literal.
Sequence length is fixed by the prompt: a different prompt length is a different program.
"""
import argparse
import json
import math
import os
import sys

import numpy as np

EPS = 1e-5


# ------------------------------------------------------------------ float64 reference
def _gelu_tanh(x):
    return 0.5 * x * (1.0 + np.tanh(math.sqrt(2.0 / math.pi) * (x + 0.044715 * x ** 3)))


def _layer_norm(x, g, b):
    mu = x.mean(axis=-1, keepdims=True)
    var = ((x - mu) ** 2).mean(axis=-1, keepdims=True)
    return (x - mu) / np.sqrt(var + EPS) * g + b


def reference_logits(wdir, cfg, ids):
    """GPT-2 forward in float64 from the exported .npy files. Returns (seq, vocab)."""
    L, D, H = cfg["n_layer"], cfg["n_embd"], cfg["n_head"]
    HD = D // H
    S = len(ids)

    def ld(name):
        return np.load(os.path.join(wdir, name + ".npy")).astype(np.float64)

    wte = ld("wte")
    x = wte[ids] + ld("wpe")[:S]
    causal = np.tril(np.ones((S, S), dtype=bool))
    for i in range(L):
        p = lambda n: ld(f"h{i}_{n}")
        h = _layer_norm(x, p("ln1_g"), p("ln1_b"))
        qkv = h @ p("qkv_w") + p("qkv_b")
        q, k, v = (t.reshape(S, H, HD).transpose(1, 0, 2) for t in (qkv[:, :D], qkv[:, D:2 * D], qkv[:, 2 * D:]))
        s = (q @ k.transpose(0, 2, 1)) / math.sqrt(HD)
        s = np.where(causal, s, -1e9)
        e = np.exp(s - s.max(axis=-1, keepdims=True))
        a = e / e.sum(axis=-1, keepdims=True)
        c = (a @ v).transpose(1, 0, 2).reshape(S, D)
        x = x + c @ p("proj_w") + p("proj_b")
        h = _layer_norm(x, p("ln2_g"), p("ln2_b"))
        x = x + _gelu_tanh(h @ p("fc_w") + p("fc_b")) @ p("out_w") + p("out_b")
    x = _layer_norm(x, ld("lnf_g"), ld("lnf_b"))
    return x @ wte.T


# ------------------------------------------------------------------ program generator
def emit_program(cfg, ids, wdir, logits_path):
    L, D, H, V = cfg["n_layer"], cfg["n_embd"], cfg["n_head"], cfg["vocab"]
    HD, S, F = D // H, len(ids), 4 * D
    scale = f"{1.0 / math.sqrt(HD):.10f}"
    out = []
    w = out.append
    w("// GPT-2 forward pass in TensorLang -- GENERATED by tools/make_gpt2_demo.py, do not edit.")
    w(f"// {L} layers, d={D}, {H} heads, vocab {V}; prompt token ids {list(map(int, ids))} (seq {S}).")
    w("// Built from existing operations only: embedding, layer_norm, matmul, slice, reshape, transpose,")
    w("// softmax, tanh. Weights come from tools/export_gpt2_weights.py (one .npy per tensor).")
    w("")
    w("""fn gelu_tanh(x: Tensor[M, N]) -> Tensor[M, N] {
    // GPT-2's gelu_new: 0.5 x (1 + tanh(sqrt(2/pi) (x + 0.044715 x^3)))
    let c0: Tensor[f32, (1,)] = [0.7978845608]
    let c1: Tensor[f32, (1,)] = [0.044715]
    let half: Tensor[f32, (1,)] = [0.5]
    let one: Tensor[f32, (1,)] = [1.0]
    let x2 = mult(x, x)
    let x3 = mult(x2, x)
    let cube = mult(x3, c1)
    let inner = add(x, cube)
    let arg = mult(inner, c0)
    let t = tanh(arg)
    let onept = add(t, one)
    let hx = mult(x, half)
    let r = mult(hx, onept)
    return r
}
""")
    params = [("x", f"({S}, {D})"), ("mask", f"({S}, {S})"),
              ("ln1_g", f"({D},)"), ("ln1_b", f"({D},)"),
              ("qkv_w", f"({D}, {3 * D})"), ("qkv_b", f"({3 * D},)"),
              ("proj_w", f"({D}, {D})"), ("proj_b", f"({D},)"),
              ("ln2_g", f"({D},)"), ("ln2_b", f"({D},)"),
              ("fc_w", f"({D}, {F})"), ("fc_b", f"({F},)"),
              ("out_w", f"({F}, {D})"), ("out_b", f"({D},)")]
    plist = ", ".join(f"{n}: Tensor[f32, {s}]" for n, s in params)
    w(f"""fn gpt2_block({plist}) -> Tensor[f32, ({S}, {D})] {{
    let scale: Tensor[f32, (1,)] = [{scale}]
    // attention (pre-LN), fused QKV, {H} heads
    let n1 = layer_norm(x, axis=1)
    let n1g = mult(n1, ln1_g)
    let h1 = add(n1g, ln1_b)
    let qkv_raw = matmul(h1, qkv_w)
    let qkv = add(qkv_raw, qkv_b)
    let q2 = qkv[:, 0:{D}]
    let k2 = qkv[:, {D}:{2 * D}]
    let v2 = qkv[:, {2 * D}:{3 * D}]
    let q3 = reshape(q2, ({S}, {H}, {HD}))
    let k3 = reshape(k2, ({S}, {H}, {HD}))
    let v3 = reshape(v2, ({S}, {H}, {HD}))
    let qh = transpose(q3, axes=(1, 0, 2))
    let kh = transpose(k3, axes=(1, 0, 2))
    let vh = transpose(v3, axes=(1, 0, 2))
    let kt = transpose(kh, axes=(0, 2, 1))
    let qk = matmul(qh, kt)
    let scores = mult(qk, scale)
    let masked = add(scores, mask)
    let attnw = softmax(masked, axis=2)
    let ctxh = matmul(attnw, vh)
    let ctxt = transpose(ctxh, axes=(1, 0, 2))
    let ctx = reshape(ctxt, ({S}, {D}))
    let proj_raw = matmul(ctx, proj_w)
    let attn_out = add(proj_raw, proj_b)
    let x1 = add(x, attn_out)
    // feed-forward (pre-LN)
    let n2 = layer_norm(x1, axis=1)
    let n2g = mult(n2, ln2_g)
    let h2 = add(n2g, ln2_b)
    let f1_raw = matmul(h2, fc_w)
    let f1 = add(f1_raw, fc_b)
    let f1g = gelu_tanh(f1)
    let f2_raw = matmul(f1g, out_w)
    let ffn_out = add(f2_raw, out_b)
    let x2 = add(x1, ffn_out)
    return x2
}}
""")
    def load(name, shape):
        w(f'let {name}: Tensor[f32, {shape}] = load("{wdir}/{name}.npy")')

    load("wte", f"({V}, {D})")
    load("wpe", f"({cfg['n_ctx']}, {D})")
    load("lnf_g", f"({D},)")
    load("lnf_b", f"({D},)")
    shapes = dict(params)
    for i in range(L):
        for n in ["ln1_g", "ln1_b", "qkv_w", "qkv_b", "proj_w", "proj_b", "ln2_g", "ln2_b", "fc_w", "fc_b", "out_w", "out_b"]:
            load(f"h{i}_{n}", shapes[n])
    w("")
    w(f"let tokens: Tensor[f32, ({S},)] = [" + ", ".join(f"{int(t)}.0" for t in ids) + "]")
    w(f"let positions: Tensor[f32, ({S},)] = [" + ", ".join(f"{i}.0" for i in range(S)) + "]")
    w("let neg: Tensor[f32, (1,)] = [-1000000000.0]")
    w("let one: Tensor[f32, (1,)] = [1.0]")
    w(f"let row: Tensor[f32, ({S}, 1)] = [" + ", ".join(f"[{i}.0]" for i in range(S)) + "]")
    w(f"let col: Tensor[f32, (1, {S})] = [[" + ", ".join(f"{i}.0" for i in range(S)) + "]]")
    w("")
    w("// causal mask: 0 where row >= col, -1e9 where blocked")
    w("let diff = minus(row, col)")
    w("let allowed = diff >= 0.0")
    w("let blocked = minus(one, allowed)")
    w("let mask = mult(blocked, neg)")
    w("")
    w("let tok_emb = embedding(tokens, wte)")
    w("let pos_emb = embedding(positions, wpe)")
    w("let x_0 = add(tok_emb, pos_emb)")
    for i in range(L):
        args = ", ".join([f"x_{i}", "mask"] + [f"h{i}_{n}" for n in
                         ["ln1_g", "ln1_b", "qkv_w", "qkv_b", "proj_w", "proj_b", "ln2_g", "ln2_b", "fc_w", "fc_b", "out_w", "out_b"]])
        w(f"let x_{i + 1} = gpt2_block({args})")
    w("")
    w("// final layer norm and the tied output projection (wte transposed)")
    w(f"let nf = layer_norm(x_{L}, axis=1)")
    w("let nfg = mult(nf, lnf_g)")
    w("let hf = add(nfg, lnf_b)")
    w("let wte_t = transpose(wte, axes=(1, 0))")
    w("let logits = matmul(hf, wte_t)")
    w(f'save(logits, "{logits_path}")')
    w(f"let last_logits = logits[{S - 1}:{S}, :]")
    w("let next_token = argmax(last_logits, axis=1)")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--weights", default="build/gpt2")
    ap.add_argument("--prompt", default="The capital of France is")
    ap.add_argument("--ids", default=None)
    ap.add_argument("--out", default="build/gpt2_forward.tl")
    ap.add_argument("--logits", default="build/gpt2_logits.npy", help="where the program saves its logits")
    ap.add_argument("--ref-out", default="build/gpt2_ref_logits.npy")
    ap.add_argument("--ref-generate", type=int, default=0)
    ap.add_argument("--shapes-only", action="store_true")
    args = ap.parse_args()

    if args.shapes_only:
        cfg = dict(n_layer=12, n_embd=768, n_head=12, vocab=50257, n_ctx=1024)
    else:
        cfg = json.load(open(os.path.join(args.weights, "config.json")))
    tok = None
    if not args.shapes_only and args.ids is None:
        try:
            from tokenizers import Tokenizer
        except ImportError:
            sys.exit("pip install tokenizers  (or pass --ids)")
        tok = Tokenizer.from_file(os.path.join(args.weights, "tokenizer.json"))
    if args.ids is not None:
        ids = [int(t) for t in args.ids.split(",")]
    elif tok is not None:
        ids = tok.encode(args.prompt).ids
    else:
        ids = [464, 3139, 286, 4881, 318, 262]   # "The capital of France is the"
    if len(ids) > cfg["n_ctx"]:
        sys.exit(f"prompt has {len(ids)} tokens, the model's context is {cfg['n_ctx']}")

    os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
    with open(args.out, "w") as f:
        f.write(emit_program(cfg, ids, args.weights, args.logits))
    print(f"wrote {args.out}  ({len(ids)} tokens: {ids})")

    if args.shapes_only:
        return
    ref = reference_logits(args.weights, cfg, ids)
    np.save(args.ref_out, ref.astype(np.float32))
    nxt = int(ref[-1].argmax())
    shown = tok.decode([nxt]) if tok else ""
    print(f"reference next token: id {nxt} {shown!r}; saved {args.ref_out}  shape {ref.shape}")
    if tok is not None:
        top = np.argsort(ref[-1])[::-1][:5]
        print("reference top-5:", [(int(t), tok.decode([int(t)])) for t in top])
    if args.ref_generate and tok is not None:
        seq = list(ids)
        for _ in range(args.ref_generate):
            seq.append(int(reference_logits(args.weights, cfg, seq)[-1].argmax()))
        print("reference greedy continuation:", repr(tok.decode(seq)))


if __name__ == "__main__":
    main()
